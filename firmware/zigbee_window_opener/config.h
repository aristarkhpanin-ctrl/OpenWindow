#pragma once

// ---------------------------------------------------------------------------
//  1. РАСПИНОВКА (ESP32-C6-DevKitC-1 / ESP32-C6 SuperMini)
// ---------------------------------------------------------------------------
//  Не занимайте GPIO12/13 — это USB. GPIO4/5/8/9/15 — strapping-пины,
//  их можно использовать, но не как выходы, тянущие уровень при старте.

#define PIN_MOTOR_IN1      2    // DRV8871 IN1  (ШИМ)
#define PIN_MOTOR_IN2      3    // DRV8871 IN2  (ШИМ)

// Все пины ниже выведены и на DevKitC-1, и на SuperMini
#define PIN_LIMIT_CLOSED  18    // концевик «окно закрыто»   (в GND, INPUT_PULLUP)
#define PIN_LIMIT_OPEN    19    // концевик «окно открыто»   (в GND, INPUT_PULLUP)

#define PIN_I2C_SDA        6    // INA219 (датчик тока) и опциональный SHT4x
#define PIN_I2C_SCL        7

#define PIN_BUTTON         9    // кнопка BOOT на плате
#define PIN_RGB_LED        8    // встроенный адресный светодиод DevKitC-1

// ---------------------------------------------------------------------------
//  2. МЕХАНИКА (значения измерены по STL из папки pok016/)
// ---------------------------------------------------------------------------
#define STROKE_MM              100   // рабочий ход рейки, мм (зубчатая часть 112 мм)
#define DEFAULT_TRAVEL_MS     9000   // ход из края в край до калибровки, мс
#define MAX_TRAVEL_FACTOR      1.4f  // аварийный стоп при времени > калибровка × этого

// ---------------------------------------------------------------------------
//  3. МОТОР И ШИМ
// ---------------------------------------------------------------------------
#define PWM_FREQ_HZ        20000   // 20 кГц — выше слышимого диапазона
#define PWM_RESOLUTION        10   // 10 бит → значения 0..1023
#define PWM_MAX             1023

#define DUTY_RUN             900   // рабочая скважность (≈88 % от 12 В)
#define DUTY_MIN             350   // минимум, при котором мотор ещё крутится
#define RAMP_MS              350   // плавный разгон/торможение, мс

// Инвертировать направление, если окно едет «наоборот»
#define MOTOR_INVERT           0   // 0 или 1

// ---------------------------------------------------------------------------
//  4. ЗАЩИТА ОТ ЗАЩЕМЛЕНИЯ (по току, INA219)
// ---------------------------------------------------------------------------
#define USE_INA219             1   // 0 — собрать без датчика тока
#define INA219_ADDR         0x40
#define INA219_SHUNT_OHM    0.1f   // шунт на типовом модуле GY-219

#define CURRENT_STALL_A     1.20f  // порог «упёрлись», А — подберите по факту!
#define STALL_CONFIRM_MS      250  // столько мс подряд ток должен быть выше порога
#define INRUSH_IGNORE_MS      600  // игнорировать пусковой ток первые N мс
#define BACKOFF_MS            700  // на сколько отъехать назад после защемления

// ---------------------------------------------------------------------------
//  5. КОНЦЕВИКИ
// ---------------------------------------------------------------------------
#define USE_LIMIT_SWITCHES     1   // 0 — работать только по времени и току
#define DEBOUNCE_MS           25

// ---------------------------------------------------------------------------
//  6. ZIGBEE
// ---------------------------------------------------------------------------
#define ZB_ENDPOINT           10
#define ZB_MANUFACTURER  "DIY"
#define ZB_MODEL         "OpenWindow-pok16"

// Роль: ROUTER — устройство постоянно запитано и ретранслирует сеть.
// Если питаете от аккумулятора — поменяйте на ZIGBEE_END_DEVICE.
#define ZB_ROLE          ZIGBEE_ROUTER

